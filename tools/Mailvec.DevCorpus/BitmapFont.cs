    /// <summary>
    /// Renders black-on-white text into an 8-bit grayscale buffer (row-major,
    /// 0 = black, 255 = white). Lowercase is drawn as uppercase; any other
    /// character outside the font throws, so a typo can't become a blank.
    /// </summary>
    public static (int Width, int Height, byte[] Pixels) Render(IReadOnlyList<string> lines, int scale, int margin)
    {
        const int cell = 6;   // 5 px glyph + 1 px spacing
        const int lineH = 10; // 7 px glyph + 3 px leading
        var cols = lines.Max(l => l.Length);
        var w = margin * 2 + cols * cell * scale;
        var h = margin * 2 + lines.Count * lineH * scale;
        var pixels = new byte[w * h];
        Array.Fill(pixels, (byte)255);

        for (var li = 0; li < lines.Count; li++)
        {
            var line = lines[li].ToUpperInvariant();
            for (var ci = 0; ci < line.Length; ci++)
            {
                if (!Glyphs.TryGetValue(line[ci], out var glyph))
                    throw new ArgumentException($"'{line[ci]}' is not in the bitmap font", nameof(lines));
                for (var gy = 0; gy < 7; gy++)
                for (var gx = 0; gx < 5; gx++)
                {
                    if (glyph[gy][gx] != '1') continue;
                    var x0 = margin + (ci * cell + gx) * scale;
                    var y0 = margin + (li * lineH + gy) * scale;
                    for (var dy = 0; dy < scale; dy++)
                        Array.Fill(pixels, (byte)0, (y0 + dy) * w + x0, scale);
                }
            }
        }
        return (w, h, pixels);
    }
